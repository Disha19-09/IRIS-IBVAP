import { useMemo, useState, useEffect } from "react";
import { Image, ShieldAlert, Camera, Clock, User, Car,} from "lucide-react";
import { useAlerts } from "../api/useAlerts.js";
import { getEventTypeLabel, getSnapshotUrl } from "../api/api.js";

function Evidence() {
  const { alerts } = useAlerts();
  const evidence = useMemo(() => alerts.filter((alert) => alert.snapshot_path), [alerts]);
  const [selectedEvidenceId, setSelectedEvidenceId] = useState(null);

  useEffect(() => {
    if (!evidence.length) {
      setSelectedEvidenceId(null);
      return;
    }

    if (!selectedEvidenceId || !evidence.some((alert) => alert.id === selectedEvidenceId)) {
      setSelectedEvidenceId(evidence[0].id ?? evidence[0].timestamp ?? null);
    }
  }, [evidence, selectedEvidenceId]);

  const selectedEvidence = evidence.find((alert) => (alert.id ?? alert.timestamp) === selectedEvidenceId) || evidence[0] || null;
  const latestEvidence = evidence[0] || null;

  function formatTimestamp(timestamp) {
    const date = new Date(timestamp);
    if (!Number.isFinite(date.getTime())) return "Unknown time";
    return date.toLocaleString([], { 
      month: 'short', 
      day: 'numeric', 
      hour: '2-digit', 
      minute: '2-digit', 
      second: '2-digit' 
    });
  }

  return (
    <div className="evidence-page">
      {/* Page Header */}
      <div className="page-header">
        <div>
          <span className="eyebrow">EVENT EVIDENCE</span>
          <h1>Evidence</h1>
          <p>
            Review snapshots captured from AI-detected security events.
          </p>
        </div>

        <div className="system-badge">
          <span className="status-dot"></span>
          EVIDENCE MONITORING ACTIVE
        </div>
      </div>

      {/* Evidence Summary */}
      <section className="stats-grid">
        <div className="stat-card">
          <div className="stat-icon">
            <Image size={18} />
          </div>

          <div>
            <span className="stat-label">SNAPSHOTS</span>
            <strong>{evidence.length}</strong>
            <small>Current session</small>
          </div>
        </div>

        <div className="stat-card">
          <div className="stat-icon alert-icon">
            <ShieldAlert size={18} />
          </div>

          <div>
            <span className="stat-label">EVENT EVIDENCE</span>
            <strong>{evidence.length}</strong>
            <small>AI-detected events</small>
          </div>
        </div>

        <div className="stat-card">
          <div className="stat-icon">
            <Camera size={18} />
          </div>

          <div>
            <span className="stat-label">SOURCE CAMERA</span>
            <strong>CAM-01</strong>
            <small>Active RTSP stream</small>
          </div>
        </div>

        <div className="stat-card">
          <div className="stat-icon">
            <Clock size={18} />
          </div>

          <div>
            <span className="stat-label">LATEST CAPTURE</span>
            <strong>{latestEvidence ? formatTimestamp(latestEvidence.timestamp).split(' ')[1] : "—"}</strong>
            <small>{latestEvidence ? formatTimestamp(latestEvidence.timestamp).split(' ')[0] : "Waiting for event"}</small>
          </div>
        </div>
      </section>

      {/* Evidence Viewer */}
      <section className="evidence-layout">
        <div className="panel evidence-viewer-panel">
          <div className="panel-header">
            <div>
              <span className="panel-kicker">EVIDENCE VIEWER</span>
              <h2>{selectedEvidence ? "Selected Snapshot" : "Latest Snapshot"}</h2>
            </div>

            <Image size={18} />
          </div>

          <div className="evidence-preview">
            {selectedEvidence ? <img src={getSnapshotUrl(selectedEvidence.snapshot_path, selectedEvidence.timestamp)} alt="Selected event evidence" /> : <Image size={44} />}
            <span>{selectedEvidence ? getEventTypeLabel(selectedEvidence.event_type, selectedEvidence.event_description) : "No evidence snapshot available"}</span>
            <small>{selectedEvidence ? formatTimestamp(selectedEvidence.timestamp) : "Event snapshots will appear here when generated by the AI pipeline."}</small>
          </div>
        </div>

        {/* Evidence Details */}
        <div className="panel evidence-details-panel">
          <div className="panel-header">
            <div>
              <span className="panel-kicker">EVENT DETAILS</span>
              <h2>Snapshot Information</h2>
            </div>

            <ShieldAlert size={18} />
          </div>

          <div className="evidence-detail-empty">
            <Image size={26} />
            <p>{selectedEvidence ? selectedEvidence.object_type || "Unknown object" : "No evidence selected."}</p>
            <span>
              {selectedEvidence 
                ? `${formatTimestamp(selectedEvidence.timestamp)} · Camera: ${selectedEvidence.camera_id} · Track: ${selectedEvidence.track_id ?? "unknown"}` 
                : "Event type, camera, object and timestamp will appear when evidence is available."}
            </span>
          </div>
        </div>
      </section>

      {/* Evidence Log */}
      <section className="panel evidence-log-panel">
        <div className="panel-header">
          <div>
            <span className="panel-kicker">EVIDENCE LOG</span>
            <h2>Captured Evidence</h2>
          </div>

          <Clock size={18} />
        </div>

        {evidence.length ? (
          <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(210px, 1fr))", gap: "16px", padding: "20px" }}>
            {evidence.map((alert, index) => (
              <button
                key={alert.id ?? `${alert.timestamp}-${index}`}
                type="button"
                onClick={() => setSelectedEvidenceId(alert.id ?? alert.timestamp ?? index)}
                style={{
                  background: "#0b1726",
                  border: (alert.id ?? alert.timestamp ?? index) === (selectedEvidenceId ?? evidence[0].id ?? evidence[0].timestamp ?? 0)
                    ? "1px solid #38bdf8"
                    : "1px solid #1f2f43",
                  borderRadius: "12px",
                  padding: "12px",
                  color: "#e5f3ff",
                  textAlign: "left",
                  cursor: "pointer",
                  display: "flex",
                  flexDirection: "column",
                  gap: "10px",
                  overflow: "hidden"
                }}
              >
                <img
                  src={getSnapshotUrl(alert.snapshot_path, alert.timestamp)}
                  alt={getEventTypeLabel(alert.event_type, alert.event_description) || "Evidence snapshot"}
                  style={{ width: "100%", height: "120px", objectFit: "cover", borderRadius: "8px", border: "1px solid #203149" }}
                />
                <div>
                  <div style={{ fontSize: "12px", color: "#7dd3fc", textTransform: "uppercase", letterSpacing: "0.08em" }}>
                    {getEventTypeLabel(alert.event_type, alert.event_description)}
                  </div>
                  <div style={{ marginTop: "6px", fontSize: "13px", color: "#dbeafe" }}>
                    {formatTimestamp(alert.timestamp)}
                  </div>
                  <div style={{ marginTop: "2px", fontSize: "12px", color: "#94a3b8" }}>
                    {alert.object_type || "Unknown object"} · Track #{alert.track_id ?? "unknown"}
                  </div>
                </div>
              </button>
            ))}
          </div>
        ) : (
          <div className="evidence-log-empty">
            <span>No evidence snapshots recorded in this session.</span>
          </div>
        )}
      </section>

      {/* Supported Evidence Metadata */}
      <section className="evidence-meta-grid">
        <div className="panel evidence-meta-card">
          <User size={18} />

          <div>
            <span>OBJECT</span>
            <strong>Person / Track ID</strong>
          </div>
        </div>

        <div className="panel evidence-meta-card">
          <Car size={18} />

          <div>
            <span>VEHICLE</span>
            <strong>Vehicle / Plate</strong>
          </div>
        </div>

        <div className="panel evidence-meta-card">
          <Camera size={18} />

          <div>
            <span>SOURCE</span>
            <strong>CAM-01</strong>
          </div>
        </div>

        <div className="panel evidence-meta-card">
          <Clock size={18} />

          <div>
            <span>TIMESTAMP</span>
            <strong>Event time</strong>
          </div>
        </div>
      </section>
    </div>
  );
}

export default Evidence;